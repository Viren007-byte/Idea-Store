import { test, expect } from '@playwright/test'

test('home, navigation, theme, and mobile layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Big things start/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'A second life for everyday things' })).toBeVisible()
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Toggle color theme' }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Our purpose' }).click()
  await expect(page.getByRole('heading', { name: 'Every idea deserves a place to begin.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/about-mobile-dark.png', fullPage: true })
  expect(errors).toEqual([])
})

test('member can register, restore a session, manage ideas and profile, and comment', async ({ page }) => {
  const email = `member-${Date.now()}@example.test`
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/login/)
  await page.getByRole('link', { name: 'Create an account', exact: true }).click()
  await page.getByLabel('First name').fill('Jamie')
  await page.getByLabel('Last name').fill('River')
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel(/^Password/).fill('BrowserTest123!')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel(/^Password/).fill('BrowserTest123!')
  await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
  await expect(page).toHaveURL(/\/dashboard/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Room for your next big thing.' })).toBeVisible()
  await page.goto('/ideas/new')
  await page.getByLabel('Give your idea a title').fill('A private browser test notebook')
  await page.getByLabel('The idea in a nutshell').fill('A place to capture a thought and grow it over time.')
  await page.getByLabel('Tell the whole story').fill('Build a thoughtful notebook that helps people capture ideas, refine the details, and choose when to share them.')
  await page.getByLabel('Tags', { exact: true }).fill('notebook, learning')
  await page.getByRole('button', { name: 'Save to my vault' }).click()
  await expect(page.getByRole('heading', { name: 'A private browser test notebook' })).toBeVisible()
  await expect(page.getByText('This idea is in your private vault.')).toBeVisible()
  const url = page.url()
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Who can see this?').click()
  await page.getByRole('option', { name: 'Everyone — community' }).click()
  await page.getByRole('button', { name: 'Save and publish' }).click()
  await expect(page.getByLabel('Add a fresh perspective')).toBeVisible()
  await page.getByLabel('Add a fresh perspective').fill('A useful idea with room to grow.')
  await page.getByRole('button', { name: 'Post comment' }).click()
  await expect(page.getByText('A useful idea with room to grow.', { exact: true })).toBeVisible()
  await page.goto('/profile')
  await page.getByLabel('Occupation', { exact: true }).fill('Design student')
  await page.getByLabel('A little about you').fill('I enjoy making useful things.')
  await page.getByLabel('GitHub URL').fill('https://github.com/example')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByText('Your profile is up to date', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Occupation', { exact: true })).toHaveValue('Design student')
  await page.goto(url)
  await page.getByRole('button', { name: 'Delete', exact: true }).first().click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard/)
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await page.goto('/profile')
  await expect(page).toHaveURL(/\/login/)
})

test('admin can inspect accounts and moderate published content', async ({ page }) => {
  await page.request.post('/api/v1/user/register', { data: { firstName: 'Moderation', lastName: 'Member', email: `moderation-${Date.now()}@example.test`, password: 'BrowserTest123!' } })
  await page.goto('/login')
  await page.getByLabel('Email address').fill('admin@example.test')
  await page.getByLabel(/^Password/).fill('BrowserTest123!')
  await page.getByRole('button', { name: 'Log in', exact: true }).last().click()
  await expect(page).toHaveURL(/\/dashboard/)
  await page.getByRole('link', { name: 'Admin', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Keep good ideas growing.' })).toBeVisible()
  await expect(page.getByText('Database: connected.')).toBeVisible()
  const row = page.getByRole('row').filter({ hasText: 'Moderation Member' })
  await row.getByRole('button', { name: 'Suspend' }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(row.getByText('Suspended', { exact: true })).toBeVisible()
  await row.getByRole('button', { name: 'Restore' }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(row.getByText('Active', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Published content' }).click()
  const content = page.getByRole('row').filter({ hasText: 'A calmer corner of the internet' })
  await content.getByRole('button', { name: 'Remove' }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(content).toHaveCount(0)
  await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true })
})
